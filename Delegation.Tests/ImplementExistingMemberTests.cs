using static Macaron.Delegation.Tests.Helper;

namespace Macaron.Delegation.Tests;

[TestFixture]
public sealed class ImplementExistingMemberTests
{
    private const string Contract =
        """
        using Macaron.InterfaceDelegation;

        namespace Macaron.Delegation.Tests;

        public interface IFoo
        {
            void MethodA();

            void MethodB();
        }
        """;

    [TestCase("Implement(typeof(IFoo))")]
    [TestCase("Implement(typeof(IFoo), Mode = ImplementationMode.Auto)")]
    [TestCase("Implement(typeof(IFoo), Mode = ImplementationMode.Explicit)")]
    public void ExplicitImplementation_IsGeneratedAlongsideExistingImplicitMember(string attribute)
    {
        AssertGeneratedCode(
            sourceCode: Contract + $$"""

                public partial class Wrapper : IFoo
                {
                    [{{attribute}}]
                    private readonly IFoo _impl = null!;

                    public void MethodA() { }
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class Wrapper
                    {
                        #region global::Macaron.Delegation.Tests.IFoo
                        void global::Macaron.Delegation.Tests.IFoo.MethodA()
                            => _impl.MethodA();

                        void global::Macaron.Delegation.Tests.IFoo.MethodB()
                            => _impl.MethodB();
                        #endregion
                    }
                }

                """
        );
    }

    [TestCase("Implement(typeof(IFoo))")]
    [TestCase("Implement(typeof(IFoo), Mode = ImplementationMode.Auto)")]
    [TestCase("Implement(typeof(IFoo), Mode = ImplementationMode.Explicit)")]
    public void ExplicitImplementation_SkipsExistingExplicitMember(string attribute)
    {
        AssertGeneratedCode(
            sourceCode: Contract + $$"""

                public partial class Wrapper : IFoo
                {
                    [{{attribute}}]
                    private readonly IFoo _impl = null!;

                    void IFoo.MethodA() { }
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class Wrapper
                    {
                        #region global::Macaron.Delegation.Tests.IFoo
                        void global::Macaron.Delegation.Tests.IFoo.MethodB()
                            => _impl.MethodB();
                        #endregion
                    }
                }

                """
        );
    }

    [TestCase("public void MethodA() { }")]
    [TestCase("void IFoo.MethodA() { }")]
    public void ImplicitImplementation_SkipsExistingImplementation(string existingMember)
    {
        AssertGeneratedCode(
            sourceCode: Contract + $$"""

                public partial class Wrapper : IFoo
                {
                    [Implement(typeof(IFoo), Mode = ImplementationMode.Implicit)]
                    private readonly IFoo _impl = null!;

                    {{existingMember}}
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class Wrapper
                    {
                        #region global::Macaron.Delegation.Tests.IFoo
                        public void MethodB()
                            => _impl.MethodB();
                        #endregion
                    }
                }

                """
        );
    }

    [Test]
    public void SkipsAbstractMembers_InSameClass_When_GeneratingDelegation()
    {
        AssertGeneratedCode(
            sourceCode:
                """
                namespace Macaron.Delegation.Tests;
                using Macaron.InterfaceDelegation;

                public interface IAbstractExample
                {
                    int GetAnswer();

                    void DoSomething();
                }

                public class AbstractExampleImpl : IAbstractExample
                {
                    public int GetAnswer() => 42;

                    public void DoSomething() { }
                }

                public abstract partial class TestAbstractDelegation : IAbstractExample
                {
                    [Implement(typeof(IAbstractExample), Mode = ImplementationMode.Implicit)]
                    private readonly IAbstractExample _impl = new AbstractExampleImpl();

                    public abstract int GetAnswer();
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class TestAbstractDelegation
                    {
                        #region global::Macaron.Delegation.Tests.IAbstractExample
                        public void DoSomething()
                            => _impl.DoSomething();
                        #endregion
                    }
                }

                """
        );
    }

    [Test]
    public void GeneratesOverride_ForAbstractMembers_InBaseClass()
    {
        AssertGeneratedCode(
            sourceCode:
                """
                namespace Macaron.Delegation.Tests;
                using Macaron.InterfaceDelegation;

                public interface IAbstractExample
                {
                    int GetAnswer();

                    int Value { get; }
                }

                public class AbstractExampleImpl : IAbstractExample
                {
                    public int GetAnswer() => 42;

                    public int Value { get => 42; }
                }

                public abstract class TestAbstractDelegationBase
                {
                    public abstract int GetAnswer();

                    public abstract int Value { get; }
                }

                public partial class TestAbstractDelegation : TestAbstractDelegationBase, IAbstractExample
                {
                    [Implement(typeof(IAbstractExample), Mode = ImplementationMode.Implicit)]
                    private readonly IAbstractExample _impl = new AbstractExampleImpl();
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class TestAbstractDelegation
                    {
                        #region global::Macaron.Delegation.Tests.IAbstractExample
                        public override int GetAnswer()
                            => _impl.GetAnswer();

                        public override int Value
                        {
                            get => _impl.Value;
                        }
                        #endregion
                    }
                }

                """
        );
    }

    [Test]
    public void SkipsOverriddenMembers_InCurrentClass_When_GeneratingDelegation()
    {
        AssertGeneratedCode(
            sourceCode:
                """
                namespace Macaron.Delegation.Tests;
                using Macaron.InterfaceDelegation;

                public interface IAbstractExample
                {
                    int GetAnswer();

                    void DoSomething();

                    int Value { get; }
                }

                public class AbstractExampleImpl : IAbstractExample
                {
                    public int GetAnswer() => 42;

                    public void DoSomething() { }

                    public int Value { get => 42; }
                }

                public abstract class TestAbstractDelegationBase
                {
                    public abstract int GetAnswer();

                    public abstract int Value { get; }
                }

                public partial class TestAbstractDelegation : TestAbstractDelegationBase
                {
                    [Implement(typeof(IAbstractExample), Mode = ImplementationMode.Implicit)]
                    private readonly IAbstractExample _impl = new AbstractExampleImpl();

                    public override int GetAnswer() => 42;

                    public override int Value { get => 42; }
                }
                """,
            expected:
                """
                // <auto-generated />
                #nullable enable

                namespace Macaron.Delegation.Tests
                {
                    partial class TestAbstractDelegation
                    {
                        #region global::Macaron.Delegation.Tests.IAbstractExample
                        public void DoSomething()
                            => _impl.DoSomething();
                        #endregion
                    }
                }

                """
        );
    }
}
