using static Macaron.Delegation.Tests.Helper;

namespace Macaron.Delegation.Tests;

[TestFixture]
public sealed class ExposeGenerationTests
{
    [Test]
    public void SelectsSupportedMembers_WithoutDuplicatingBaseOverrides()
    {
        AssertGeneratedCode(
            sourceCode:
            """
            using System.Collections.Generic;

            namespace Macaron.Delegation.Tests;

            using Macaron.MemberExposure;

            // 베이스 클래스 멤버도 포함
            public class Base
            {
                public int BaseValue { get; }

                public void BaseMethod() { }

                // 오버라이드 된 멤버는 무시됨
                public virtual void BaseVirtualMethod() { }
            }

            public abstract class Foo : Base
            {
                // 정적 멤버는 무시됨
                public static Foo Of() => null!;

                public static int StaticValue => 42;

                // 인덱서는 무시됨
                public int this[int index]
                {
                    get => 0;
                    set { }
                }

                public List<object?> Value => null!;

                // internal은 internal로 리프팅
                internal int GetAnswer() => 42;

                public override void BaseVirtualMethod() { }

                // public인 아닌 멤버는 무시됨
                protected int HiddenAnswer() => 42;

                // abstract 멤버도 리프팅 대상
                public abstract void AbstractMethod();
            }

            public partial class Bar
            {
                [Expose(IncludeBaseTypes = true)]
                private readonly Foo _impl = null!;
            }
            """,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.Delegation.Tests
            {
                partial class Bar
                {
                    #region global::Macaron.Delegation.Tests.Foo
                    public global::System.Collections.Generic.List<object?> Value
                    {
                        get => _impl.Value;
                    }

                    internal int GetAnswer()
                        => _impl.GetAnswer();

                    public void BaseVirtualMethod()
                        => _impl.BaseVirtualMethod();

                    public void AbstractMethod()
                        => _impl.AbstractMethod();

                    public int BaseValue
                    {
                        get => _impl.BaseValue;
                    }

                    public void BaseMethod()
                        => _impl.BaseMethod();
                    #endregion
                }
            }

            """
        );
    }

    [TestCase("class")]
    [TestCase("class?")]
    public void PreservesGenericMethodConstraint(string constraint)
    {
        var result = RunGenerator(
            $$"""
            using Macaron.MemberExposure;

            public class Target
            {
                public int GetAnswer<T>() where T : {{constraint}} => 42;
            }

            public partial class Wrapper
            {
                [Expose]
                private readonly Target _impl = new();
            }
            """
        );

        AssertSuccessfulGeneration(result);

        var source = result.GeneratedSources.Single().SourceText.ToString();

        Assert.That(
            source,
            Does.Contain("public int GetAnswer<T>()")
                .And.Contain($"where T : {constraint}")
                .And.Contain("=> _impl.GetAnswer<T>();")
        );
    }

    [Test]
    public void PreservesNullableUnconstrainedGenericReturnType()
    {
        var result = RunGenerator(
            """
            using System.Collections.Generic;
            using Macaron.MemberExposure;

            public class Target
            {
                public List<T?> GetAnswer<T>() => null!;
            }

            public partial class Wrapper
            {
                [Expose]
                private readonly Target _impl = new();
            }
            """
        );

        AssertSuccessfulGeneration(result);

        var source = result.GeneratedSources.Single().SourceText.ToString();

        Assert.That(
            source,
            Does
                .Contain("public global::System.Collections.Generic.List<T?> GetAnswer<T>()")
                .And.Contain("=> _impl.GetAnswer<T>();")
        );
    }

    [Test]
    public void PreservesMethodDefaultParameters_ForValueTypePropertyTarget()
    {
        AssertGeneratedCode(
            sourceCode:
            """
            using System;

            namespace Macaron.Delegation.Tests;

            using Macaron.MemberExposure;

            public struct Foo
            {
                public void Bar(int x, int y = 42, DateTime z = new DateTime()) { }
            }

            public partial class Wrapper
            {
                [Expose]
                private Foo _impl { get; } = new();
            }
            """,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.Delegation.Tests
            {
                partial class Wrapper
                {
                    #region global::Macaron.Delegation.Tests.Foo
                    public void Bar(int x, int y = 42, global::System.DateTime z = default)
                        => _impl.Bar(x, y, z);
                    #endregion
                }
            }

            """
        );
    }
}
